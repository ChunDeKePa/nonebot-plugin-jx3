def _get_help_data(show_all: bool = False) -> dict:
    """根据是否开启全部或是否配置 Token，动态提取要展示的帮助条目"""
    if show_all or has_token():
        return ALL_HELP_DATA

    # 未配置 Token 时，仅展示免费与基础管理指令，收费指令完全不显示
    filtered = {}
    for section, commands in ALL_HELP_DATA.items():
        # 仅保留免费、管理
        valid = [item for item in commands if item[2] in ("免费", "管理")]
        if valid:
            filtered[section] = valid
    return filtered


# ===== 剑三帮助（普通用户指令，根据 Token 动态过滤） =====
cmd_help = on_command("剑三帮助", aliases={"帮助", "jx3帮助", "剑3帮助"}, rule=group_filter(), priority=5, block=True)


@cmd_help.handle()
async def handle_help(event: GroupMessageEvent):
    is_vip = has_token()
    data = _get_help_data(show_all=False)
    title = "⚔️ 剑网三助手 · 指令帮助" if is_vip else "⚔️ 剑网三助手 · 基础免费版帮助"
    img = await renderer.render(
        "help.html", 
        cache_key=f"help:{is_vip}",
        cache_ttl=None, # 重启不变
        data=data, 
        title=title
    )
    await cmd_help.finish(MessageSegment.image(img))


# ===== 全部帮助（管理员专属，展示全量所有接口及权限） =====
cmd_all_help = on_command(
    "全部帮助", 
    aliases={"完整帮助", "所有帮助", "jx3全部帮助", "管理帮助"}, 
    rule=group_filter(), 
    priority=5, 
    block=True
)


@cmd_all_help.handle()
async def handle_all_help(event: GroupMessageEvent):
    # 鉴权：超级用户或群管理员/群主
    superusers = get_driver().config.superusers
    is_admin = str(event.user_id) in superusers or event.sender.role in ("admin", "owner")
    if not is_admin:
        await cmd_all_help.finish("⚠️ 「全部帮助」仅限群管理员或主人查看，普通成员请发送「帮助」～")

    img = await renderer.render(
        "help.html", 
        cache_key="all_help",
        cache_ttl=None, # 重启不变
        data=ALL_HELP_DATA, 
        title="⚔️ 剑网三助手 · 全量指令与权限清单 (管理员)"
    )
    await cmd_all_help.finish(MessageSegment.image(img))
